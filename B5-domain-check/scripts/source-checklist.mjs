import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDirectory, "..");
const sourcePath = resolve(root, "src", "items.ca.json");
const outputPath = resolve(root, "SOURCE-CHECKLIST.md");
const bank = JSON.parse(await readFile(sourcePath, "utf8"));

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function answerSummary(item) {
  return item.errorIndex === null
    ? "Neta"
    : `Error a la frase ${item.errorIndex + 1}`;
}

const rows = [
  {
    scope: "Pràctica",
    domain: "Regla de l'activitat",
    item: bank.practice,
    answer: answerSummary(bank.practice),
  },
  ...bank.domains.flatMap((domain) =>
    domain.items.map((item) => ({
      scope: "Judici",
      domain: domain.label,
      item,
      answer: answerSummary(item),
    })),
  ),
  ...bank.transfers.map((item) => ({
    scope: "Transferència",
    domain: item.tag,
    item,
    answer: item.expected,
  })),
];

const lines = [
  "# B5 source checklist",
  "",
  "Generated from `src/items.ca.json`. Do not edit this file by hand; run",
  "`npm run sources:list` after changing the item bank.",
  "",
  `- Bank verified at: ${bank.verifiedAt}`,
  `- Source review: ${bank.reviewPolicy.sourceReview} (${bank.reviewPolicy.sourceReviewer})`,
  `- Subject-matter sign-off: ${bank.reviewPolicy.subjectMatterSignoff}`,
  `- Catalan language sign-off: ${bank.reviewPolicy.languageSignoff}`,
  "",
  "| Scope | Domain | Item | Answer key | Publisher and source | Checked | Factual review | Language review |",
  "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ...rows.map(({ scope, domain, item, answer }) => {
    const sourceLabel = item.source.url
      ? `[${item.source.publisher}: ${item.source.title}](${item.source.url})`
      : `${item.source.publisher}: ${item.source.title} (activity-defined)`;
    return `| ${escapeCell(scope)} | ${escapeCell(domain)} | \`${escapeCell(item.id)}\` | ${escapeCell(answer)} | ${escapeCell(sourceLabel)} | ${escapeCell(item.source.checkedAt)} | ${escapeCell(item.review.factual)} | ${escapeCell(item.review.language)} |`;
  }),
  "",
  "## Provenance",
  "",
  ...rows.flatMap(({ item }) => [
    `### \`${item.id}\``,
    "",
    item.provenance,
    "",
  ]),
];

const generated = `${lines.join("\n").trimEnd()}\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    console.error(
      "SOURCE-CHECKLIST.md is stale. Run `npm run sources:list` and commit it.",
    );
    process.exitCode = 1;
  } else {
    console.log(`Source checklist matches all ${rows.length} activity items.`);
  }
} else {
  await writeFile(outputPath, generated, "utf8");
  console.log(`Wrote ${outputPath}`);
}
